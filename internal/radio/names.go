func CommandName(code byte) string {
	if n, ok := commandNames[code]; ok {
		return n
	}
	return fmt.Sprintf("CMD_%d", code)
}

func ResponseName(code byte) string {
	if n, ok := responseNames[code]; ok {
		return n
	}
	return fmt.Sprintf("RESP_0x%02X", code)
}
